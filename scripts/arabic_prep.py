ONES = ["صِفْر", "وَاحِد", "اثْنَان", "ثَلَاثَة", "أَرْبَعَة", "خَمْسَة", "سِتَّة", "سَبْعَة", "ثَمَانِيَة", "تِسْعَة"]
TEENS = ["عَشَرَة", "أَحَدَ عَشَر", "اثْنَا عَشَر", "ثَلَاثَةَ عَشَر", "أَرْبَعَةَ عَشَر", "خَمْسَةَ عَشَر",
         "سِتَّةَ عَشَر", "سَبْعَةَ عَشَر", "ثَمَانِيَةَ عَشَر", "تِسْعَةَ عَشَر"]
TENS = ["", "", "عِشْرُون", "ثَلَاثُون", "أَرْبَعُون", "خَمْسُون", "سِتُّون", "سَبْعُون", "ثَمَانُون", "تِسْعُون"]


def number_words(n: int) -> str:
    if n < 10:
        return ONES[n]
    if n < 20:
        return TEENS[n - 10]
    if n < 100:
        t, o = divmod(n, 10)
        return TENS[t] if o == 0 else f"{ONES[o]} وَ{TENS[t]}"
    return " ".join(ONES[int(d)] for d in str(n))


TOKEN = re.compile(r"[+\-]?\d+(?:\.\d+)?%?|[ء-يً-ْ]+|[،.!؟:?]")


def vocalise(text: str, unknown: set[str] | None = None) -> str:
    out: list[str] = []
    for m in TOKEN.finditer(text):
        tok = m.group(0)
        if tok[0] in "+-" and len(tok) > 1 and tok[1].isdigit():
            out.append("زَائِد" if tok[0] == "+" else "نَاقِص")
            tok = tok[1:]
        if tok[0].isdigit():
            pct = tok.endswith("%")
            tok = tok.rstrip("%")
            if "." in tok:
                a, b = tok.split(".")
                out.append(number_words(int(a)) + " فَاصِلَة " + " ".join(ONES[int(d)] for d in b))
            else:
                out.append(number_words(int(tok)))
            if pct:
                out.append("بِالمِيَّة")
        elif tok in "،.!؟:?":
            out.append("،" if tok == ":" else tok)
        else:
            v = LEX.get(tok)
            if v is None:
                if unknown is not None:
                    unknown.add(tok)
                v = tok
            out.append(v)
    return " ".join(out).replace(" ،", "،").replace(" .", ".").replace(" !", "!")
